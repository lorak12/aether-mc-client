/** Loadout slots; the client's gg.kite.core.cosmetics.Slot uses the same ids. */
export const SLOTS = ["cape", "wings", "hat", "ears", "face", "boots", "back"] as const;
export type Slot = (typeof SLOTS)[number];
export type Rarity = "common" | "rare" | "epic" | "legendary";

export interface Cosmetic {
  id: string;
  slot: Slot;
  name: string;
  rarity: Rarity;
  /** Owned by everyone without a grant or purchase. */
  free: boolean;
  /** Price in coins in the store; null when it can't be bought (free, or grant-only). */
  price: number | null;
  description: string;
  /** Folder of the model/texture bundle in the client (runtime/core/src/main/resources/kite/cosmetics). */
  asset: string;
}

/** Coins by rarity for the purchasable starters. Common and rare items stay free. */
const PRICE: Record<Rarity, number | null> = { common: null, rare: null, epic: 600, legendary: 1200 };

const starter = (id: string, slot: Slot, name: string, rarity: Rarity, description: string): Cosmetic => ({
  id,
  slot,
  name,
  rarity,
  free: PRICE[rarity] === null,
  price: PRICE[rarity],
  description,
  asset: id,
});

